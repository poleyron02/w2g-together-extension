import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'
import path from 'node:path'
import { test } from 'node:test'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const index = JSON.parse(await readFile(path.join(root, 'index.json'), 'utf8'))

/** Evaluate an extension the same way the app's sandbox does. */
async function load(file, routes) {
  const code = await readFile(path.join(root, file), 'utf8')
  const requested = []
  const http = {
    get: async (url) => {
      requested.push(url)
      const match = Object.entries(routes).find(([needle]) => url.includes(needle))
      // A route value of { status, raw } returns that status and raw body text.
      const custom = match && match[1] && typeof match[1].raw === 'string' ? match[1] : null
      const status = custom ? custom.status : match ? 200 : 404
      const body = custom ? custom.raw : match ? JSON.stringify(match[1]) : ''
      return { ok: status >= 200 && status < 300, status, url, body, text: () => body, json: () => JSON.parse(body) }
    },
  }
  let ext = null
  new Function('registerExtension', 'http', 'log', `"use strict";\n${code}`)((d) => (ext = d), http, () => {})
  assert.ok(ext, `${file} must call registerExtension()`)
  return { ext, requested }
}

test('index.json hashes match the extension files', async () => {
  for (const entry of index.extensions) {
    const code = await readFile(path.join(root, entry.file))
    const sha = createHash('sha256').update(code).digest('hex')
    assert.equal(entry.sha256, sha, `${entry.id}: run "npm run index" after editing ${entry.file}`)
  }
})

test('archive-org: popular → episodes → streams', async () => {
  const { ext, requested } = await load('extensions/archive-org.js', {
    advancedsearch: {
      response: {
        numFound: 100,
        docs: [{ identifier: 'nosferatu', title: 'Nosferatu', year: '1922', description: '<b>Classic</b>' }],
      },
    },
    '/metadata/': {
      files: [
        { name: 'Nosferatu.mp4', format: 'MPEG4', size: '700000000' },
        { name: 'Nosferatu.ia.mp4', format: 'h.264 IA', size: '300000000' },
        { name: 'Nosferatu.srt', format: 'SubRip' },
        { name: 'Nosferatu.jpg', format: 'JPEG' },
      ],
    },
  })

  const page = await ext.popular(1)
  assert.equal(page.items[0].id, 'nosferatu')
  assert.equal(page.items[0].year, 1922)
  assert.equal(page.items[0].description, 'Classic')
  assert.equal(page.hasNextPage, true)
  assert.ok(requested.every((u) => new URL(u).hostname.endsWith('archive.org')))

  const episodes = await ext.episodes('nosferatu')
  assert.equal(episodes.length, 1)

  const streams = await ext.streams(episodes[0].id)
  assert.equal(streams.length, 2)
  assert.equal(streams[0].url, 'https://archive.org/download/nosferatu/Nosferatu.mp4')
  assert.match(streams[0].subtitles[0].url, /Nosferatu\.srt$/)
})

test('kisskh: popular → search → episodes → signed streams', async () => {
  const { ext, requested } = await load('extensions/kisskh.js', {
    'DramaList/List': {
      page: 1,
      totalCount: 100,
      data: [{ id: 10606, title: 'Speed and Love', episodesCount: 29, thumbnail: 'https://img.example/a.jpg' }],
    },
    'DramaList/Search': [{ id: 1995, title: 'Parasite', episodesCount: 1, thumbnail: null }],
    'DramaList/Drama/10606': {
      type: 'TVSeries',
      episodes: [
        { id: 201756, number: 29.6 },
        { id: 201001, number: 1 },
      ],
    },
    'DramaList/Episode/201756.png': { Video: 'https://hls.example/Ep35_index.m3u8' },
    'Sub/201756': [
      { src: 'https://sub.example/Indonesia-EP35.srt.txt1', label: 'Indonesia', land: 'id', default: false },
      { src: 'https://sub.example/English-EP35.srt.txt1', label: 'English', land: 'en', default: true },
      { src: 'https://sub.example/Plain-EP35.srt', label: 'Plain', land: 'en', default: false },
    ],
  })

  const page = await ext.popular(1)
  assert.deepEqual(page.items[0], { id: '10606', title: 'Speed and Love', poster: 'https://img.example/a.jpg', kind: 'series' })
  assert.equal(page.hasNextPage, true)

  const search = await ext.search('parasite', 1)
  assert.equal(search.items[0].kind, 'movie')
  assert.equal((await ext.search('parasite', 2)).items.length, 0)

  const episodes = await ext.episodes('10606')
  assert.deepEqual(episodes.map((e) => e.number), [1, 29.6])

  const [stream] = await ext.streams('201756')
  assert.equal(stream.url, 'https://hls.example/Ep35_index.m3u8')
  assert.equal(stream.subtitles[0].label, 'English')
  assert.deepEqual(stream.subtitles[0].cipher, { algorithm: 'aes-cbc', key: 'AmSmZVcH93UQUezi', iv: 'ReBKWW8cqdjPEnF6' })
  assert.equal(stream.subtitles[2].cipher, undefined)

  // Token generated by the site's own common.js for episode 201756.
  const episodeUrl = requested.find((u) => u.includes('/Episode/'))
  assert.match(episodeUrl, /kkey=238D760DB6FD3C5F0ECD7CF0C120882D8A80A89E/)
  assert.ok(requested.every((u) => new URL(u).hostname === 'kisskh.ovh'))
})

test('kisskh: falls back to a mirror when Cloudflare blocks one, and remembers it', async () => {
  const blocked = { status: 403, raw: '<title>Attention Required! | Cloudflare</title>' }
  const { ext, requested } = await load('extensions/kisskh.js', {
    'kisskh.ovh/': blocked,
    'kisskh.id/api/DramaList/List': { page: 1, totalCount: 1, data: [{ id: 1, title: 'A', episodesCount: 2 }] },
    'kisskh.id/api/DramaList/Search': [],
  })

  const page = await ext.popular(1)
  assert.equal(page.items[0].id, '1')
  assert.deepEqual(requested.map((u) => new URL(u).hostname), ['kisskh.ovh', 'kisskh.id'])

  await ext.search('x', 1)
  assert.equal(new URL(requested.at(-1)).hostname, 'kisskh.id')
  assert.equal(requested.length, 3)
})

test('kisskh: reports every mirror when all are blocked', async () => {
  const blocked = { status: 403, raw: 'cloudflare' }
  const { ext } = await load('extensions/kisskh.js', {
    'kisskh.ovh/': blocked,
    'kisskh.id/': blocked,
    'kisskh.la/': blocked,
  })
  await assert.rejects(ext.popular(1), /Every KissKH mirror blocked.*kisskh\.ovh.*kisskh\.id.*kisskh\.la/)
})
